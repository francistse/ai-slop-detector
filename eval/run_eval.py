#!/usr/bin/env python3
"""Eval harness for the ai-slop-detector.

Reads a gold set (JSONL lines: {id, lang, label, source, text}), runs the
Jev backend on every case, and writes:
  - <out>/cases.csv          one row per case with full scores
  - <out>/report.md          aggregated metrics + methodology
Ground truth labels: label=human (real forum/personal writing) or ai
(attributed model output — see ai.jsonl source fields). This is an internal
verification report, not a published accuracy claim. (Laya was removed v1.1.)
"""
import argparse
import csv
import importlib.util
import json
import os
import re
import sys

DETECT_PY = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         "..", "skill", "ai-slop-detector", "scripts", "detect.py")


def load_detect():
    spec = importlib.util.spec_from_file_location("ai_slop_detect", DETECT_PY)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def iter_gold(gold_paths):
    seen = set()
    for gp in gold_paths:
        if not os.path.exists(gp):
            print(f"[warn] gold file missing: {gp}", file=sys.stderr)
            continue
        with open(gp, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                rec = json.loads(line)
                if rec["id"] in seen:
                    continue
                seen.add(rec["id"])
                yield rec


def verdict_ok(model_verdict, true_label):
    """Map model verdict + true label to {correct, fp, fn, abstain}."""
    if model_verdict == "ambiguous":
        return "abstain"
    if model_verdict == "AI-likely":
        return "fp" if true_label == "human" else "correct"
    # human-likely (or anything else)
    return "fn" if true_label == "ai" else "correct"


def run(detect_mod, text, lang, backend):
    res, _, meta = detect_mod.score(
        text, detect_mod.TRAITS, detect_mod.DIRECT, lang=lang, backend=backend
    )
    return res, meta


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gold", action="append", default=[])
    ap.add_argument("--out", default="eval/out")
    ap.add_argument("--backends", default="jev",
                    help="comma list; only 'jev' exists since Laya was removed in v1.1")
    args = ap.parse_args()

    gold_paths = args.gold
    os.makedirs(args.out, exist_ok=True)

    detect_mod = load_detect()
    backends = [b.strip() for b in args.backends.split(",") if b.strip()]

    cases = []
    for rec in iter_gold(gold_paths):
        lang = rec.get("lang", "zh")
        for b in backends:
            r, meta = run(detect_mod, rec["text"], "auto", b)
            dlang = r.get("lang", lang)
            cases.append(
                {
                    "id": rec["id"],
                    "lang": lang,
                    "label": rec["label"],
                    "source": rec.get("source", ""),
                    "backend": b,
                    "detected_lang": dlang,
                    "lang_ok": int(dlang == lang),
                    "verdict": r["verdict"],
                    "ai_probability": r["ai_probability"],
                    "confidence": r["confidence"],
                    "direct_signal": r["direct_signal"],
                    "qc": verdict_ok(r["verdict"], rec["label"]),
                    "cost": (meta or {}).get("cost"),
                }
            )

    # ---- write cases.csv ----
    with open(os.path.join(args.out, "cases.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(
            f,
            fieldnames=["id", "lang", "label", "source", "backend",
                        "detected_lang", "lang_ok",
                        "verdict", "ai_probability", "confidence",
                        "direct_signal", "qc", "cost"],
        )
        w.writeheader()
        w.writerows(cases)

    # ---- aggregate ----
    lines = [_report_header(gold_paths)]
    for b in backends:
        bc = [c for c in cases if c["backend"] == b]
        lines.append(_aggregate_block(b, bc))
    with open(os.path.join(args.out, "report.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"wrote {len(cases)} case-rows -> {args.out}/cases.csv")
    print(f"wrote aggregated report -> {args.out}/report.md")
    for b in backends:
        bc = [c for c in cases if c["backend"] == b]
        agg = _aggregate_block(b, bc)
        print("----")
        print(agg)


def _report_header(n_sources):
    return (
        "# ai-slop-detector — evaluation report\n\n"
        f"Generated by `eval/run_eval.py` · {len(n_sources)} gold source group(s)\n\n"
        "**Ground truth is attribution-based, not opinion:** `human` = real "
        "person-written text (LIHKG / forum), `ai` = text actually generated by "
        "a model (deepseek-v4-flash — incl. 思考哥 drafts and direct generations; "
        "see `gold/ai.jsonl` source fields). "
        "`qc` legend: `correct` / `fp` (human misjudged AI) / `fn` (AI missed) / "
        "`abstain` (called ambiguous).\n"
    )


def _aggregate_block(backend, cases):
    total = len(cases)
    humans = [c for c in cases if c["label"] == "human"]
    ais = [c for c in cases if c["label"] == "ai"]

    def rates(grp):
        n = len(grp)
        if n == 0:
            return {"correct": 0, "fp": 0, "fn": 0, "abstain": 0, "n": 0}
        q = {"correct": 0, "fp": 0, "fn": 0, "abstain": 0, "n": n}
        for c in grp:
            q[c["qc"]] += 1
        return q

    hu, ai = rates(humans), rates(ais)
    allq = rates(cases)

    acc = allq["correct"] / allq["n"] if allq["n"] else 0
    fp_rate = hu["fp"] / hu["n"] if hu["n"] else 0
    fn_rate = ai["fn"] / ai["n"] if ai["n"] else 0
    abstain = ai["abstain"] + hu["abstain"]

    avg_conf = round(sum(c["confidence"] for c in cases) / total, 3) if total else 0
    avg_ai_prob = round(sum(c["ai_probability"] for c in cases) / total, 3) if total else 0

    return (
        f"## Backend: {backend}  (N={total})\n\n"
        f"- verbatim-only accuracy: **{acc:.1%}** ({allq['correct']}/{allq['n']})\n"
        f"- human misread as AI  (FP): {hu['fp']}/{hu['n']} = **{fp_rate:.1%}**\n"
        f"- AI missed            (FN): {ai['fn']}/{ai['n']} = **{fn_rate:.1%}**\n"
        f"- abstained (ambiguous): {abstain}/{total} = {abstain/total:.1%}\n"
        f"- mean ai_probability: {avg_ai_prob:.3f} · mean confidence: {avg_conf:.3f}\n"
    )


if __name__ == "__main__":
    main()